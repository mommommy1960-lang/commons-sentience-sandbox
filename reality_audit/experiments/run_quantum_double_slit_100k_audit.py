"""100k-event sampling audit for the quantum double-slit benchmark.

This is a robustness / calibration experiment, not an ontology detector.
It asks whether finite Born-rule samples generated by the existing benchmark
track the probability profiles that the benchmark itself specifies.

Default workload:
  10 independent seeds x 100,000 detections x 2 primary conditions
  = 2,000,000 sampled detection events.

Outputs descriptive diagnostics only. Passing this experiment demonstrates
internal sampling consistency; it does NOT show that physical reality is a
simulation and it does NOT constitute laboratory evidence for new physics.
"""

from __future__ import annotations

import argparse
import json
import math
from pathlib import Path
from statistics import mean, pstdev
from typing import Any, Dict, Iterable, List

from reality_audit.benchmarks.quantum_double_slit import QSlitCondition, run_condition


def _normalise(weights: Iterable[float]) -> List[float]:
    vals = [float(x) for x in weights]
    total = sum(vals)
    if total <= 0.0:
        raise ValueError("probability profile has non-positive total weight")
    return [x / total for x in vals]


def _diagnostics(hits: List[int], expected_p: List[float]) -> Dict[str, float]:
    n = sum(hits)
    observed_p = [h / n for h in hits]
    l1 = sum(abs(o - e) for o, e in zip(observed_p, expected_p))

    chi2 = 0.0
    used_bins = 0
    max_abs_standardized_residual = 0.0
    for h, p in zip(hits, expected_p):
        expected = n * p
        if expected <= 0.0:
            continue
        used_bins += 1
        chi2 += (h - expected) ** 2 / expected
        variance = expected * (1.0 - p)
        if variance > 0.0:
            residual = abs(h - expected) / math.sqrt(variance)
            max_abs_standardized_residual = max(max_abs_standardized_residual, residual)

    dof = max(1, used_bins - 1)
    return {
        "n_events": float(n),
        "l1_distance": l1,
        "chi_square": chi2,
        "degrees_of_freedom": float(dof),
        "chi_square_per_dof": chi2 / dof,
        "max_abs_standardized_residual": max_abs_standardized_residual,
    }


def _log_likelihood(hits: List[int], p: List[float]) -> float:
    tiny = 1e-300
    return sum(h * math.log(max(prob, tiny)) for h, prob in zip(hits, p))


def run_audit(n_trials: int = 100_000, seeds: Iterable[int] = range(10)) -> Dict[str, Any]:
    seeds = list(seeds)
    rows: List[Dict[str, Any]] = []

    # Use seed 0 only to obtain the deterministic probability profiles. The
    # profiles do not depend on the random seed; only hit sampling does.
    coherent_reference = run_condition(QSlitCondition.TWO_SLIT_COHERENT, n_trials=1, seed=0)
    decohered_reference = run_condition(QSlitCondition.TWO_SLIT_DECOHERED, n_trials=1, seed=0)
    p_coherent = _normalise(coherent_reference["probability_profile"])
    p_decohered = _normalise(decohered_reference["probability_profile"])

    for seed in seeds:
        coherent = run_condition(QSlitCondition.TWO_SLIT_COHERENT, n_trials=n_trials, seed=seed)
        decohered = run_condition(QSlitCondition.TWO_SLIT_DECOHERED, n_trials=n_trials, seed=seed)

        coherent_diag = _diagnostics(coherent["hit_counts"], p_coherent)
        decohered_diag = _diagnostics(decohered["hit_counts"], p_decohered)

        coherent_llr = _log_likelihood(coherent["hit_counts"], p_coherent) - _log_likelihood(
            coherent["hit_counts"], p_decohered
        )
        decohered_llr = _log_likelihood(decohered["hit_counts"], p_decohered) - _log_likelihood(
            decohered["hit_counts"], p_coherent
        )

        rows.append(
            {
                "seed": seed,
                "coherent": coherent_diag,
                "decohered": decohered_diag,
                "coherent_log_likelihood_advantage_over_decohered": coherent_llr,
                "decohered_log_likelihood_advantage_over_coherent": decohered_llr,
            }
        )

    def summary_for(condition: str) -> Dict[str, float]:
        chi_per_dof = [row[condition]["chi_square_per_dof"] for row in rows]
        l1 = [row[condition]["l1_distance"] for row in rows]
        max_resid = [row[condition]["max_abs_standardized_residual"] for row in rows]
        return {
            "mean_chi_square_per_dof": mean(chi_per_dof),
            "std_chi_square_per_dof": pstdev(chi_per_dof),
            "min_chi_square_per_dof": min(chi_per_dof),
            "max_chi_square_per_dof": max(chi_per_dof),
            "mean_l1_distance": mean(l1),
            "max_l1_distance": max(l1),
            "mean_max_abs_standardized_residual": mean(max_resid),
            "max_abs_standardized_residual_overall": max(max_resid),
        }

    return {
        "experiment": "quantum_double_slit_100k_sampling_audit",
        "n_trials_per_condition_per_seed": n_trials,
        "seeds": seeds,
        "total_sampled_detection_events": n_trials * len(seeds) * 2,
        "coherent_reference_visibility": coherent_reference["summary"]["fringe_visibility"],
        "decohered_reference_visibility": decohered_reference["summary"]["fringe_visibility"],
        "summary": {
            "coherent": summary_for("coherent"),
            "decohered": summary_for("decohered"),
            "all_coherent_samples_prefer_coherent_model": all(
                row["coherent_log_likelihood_advantage_over_decohered"] > 0 for row in rows
            ),
            "all_decohered_samples_prefer_decohered_model": all(
                row["decohered_log_likelihood_advantage_over_coherent"] > 0 for row in rows
            ),
        },
        "runs": rows,
        "interpretation_boundary": (
            "This is an internal calibration and finite-sampling robustness check of a programmed "
            "two-path quantum-style benchmark. It can validate implementation behavior, but it cannot "
            "determine whether physical reality is simulated or establish new physics."
        ),
    }


def _write_markdown(report: Dict[str, Any], path: Path) -> None:
    s = report["summary"]
    lines = [
        "# Quantum Double-Slit 100k Sampling Audit",
        "",
        f"- Events per condition per seed: **{report['n_trials_per_condition_per_seed']:,}**",
        f"- Seeds: **{len(report['seeds'])}**",
        f"- Total sampled detection events: **{report['total_sampled_detection_events']:,}**",
        f"- Coherent reference visibility: **{report['coherent_reference_visibility']:.6f}**",
        f"- Decohered reference visibility: **{report['decohered_reference_visibility']:.6f}**",
        "",
        "## Sampling diagnostics",
        "",
        f"- Coherent mean chi-square/dof: **{s['coherent']['mean_chi_square_per_dof']:.4f}**",
        f"- Decohered mean chi-square/dof: **{s['decohered']['mean_chi_square_per_dof']:.4f}**",
        f"- Coherent mean L1 distance: **{s['coherent']['mean_l1_distance']:.4f}**",
        f"- Decohered mean L1 distance: **{s['decohered']['mean_l1_distance']:.4f}**",
        f"- Every coherent sample preferred the coherent model by likelihood: **{s['all_coherent_samples_prefer_coherent_model']}**",
        f"- Every decohered sample preferred the decohered model by likelihood: **{s['all_decohered_samples_prefer_decohered_model']}**",
        "",
        "## Interpretation boundary",
        "",
        report["interpretation_boundary"],
    ]
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--n-trials", type=int, default=100_000)
    parser.add_argument("--seeds", type=int, default=10, help="Use integer seeds 0..N-1")
    parser.add_argument("--output-dir", default="outputs/quantum_double_slit_100k")
    args = parser.parse_args()

    if args.n_trials <= 0 or args.seeds <= 0:
        raise SystemExit("--n-trials and --seeds must be positive")

    report = run_audit(args.n_trials, range(args.seeds))
    out = Path(args.output_dir)
    out.mkdir(parents=True, exist_ok=True)
    (out / "audit.json").write_text(json.dumps(report, indent=2), encoding="utf-8")
    _write_markdown(report, out / "audit.md")
    print(json.dumps(report["summary"], indent=2))


if __name__ == "__main__":
    main()
